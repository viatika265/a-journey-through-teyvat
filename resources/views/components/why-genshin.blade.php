<script>
(function () {
    function initWhyGenshin() {
        const section = document.querySelector('#why-genshin');

        if (!section || section.dataset.wgInitialized === 'true') {
            return;
        }

        section.dataset.wgInitialized = 'true';

        const cards = section.querySelectorAll('.wg-card');

        cards.forEach((card) => {
            card.addEventListener('click', () => {
                card.classList.toggle('wg-card-selected');
            });
        });
    }

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', initWhyGenshin);
    } else {
        initWhyGenshin();
    }
})();
